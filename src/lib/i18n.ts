export type StringKey = keyof (typeof strings)['en'];
export type Lang = keyof typeof strings;

const configured = (settings as { language?: string }).language;
export const lang: Lang = configured && configured in strings ? (configured as Lang) : 'en';

/** Translate an interface string, filling `{placeholders}` from `vars`. */
export function t(key: StringKey, vars: Record<string, string | number> = {}): string {
  const text: string = strings[lang][key] ?? strings.en[key];
  return text.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ''));
}
